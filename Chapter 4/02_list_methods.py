friends = ["Apple", "Orange", 5, 345.00, False, "Sujeet", "prem"]
print(friends)

# append : insertion at the end 
friends.append("Rohan")
print(friends)

# Sort : Sort the list in increasing or decreasing order
l1 = [1, 53, 56, 7, 20, 45, 200]
l1.sort()
print(l1)

#reverse : arrange the list in reverse order 
l1.reverse()
print(l1)

# insert : Insert is you to insert a number in the  list at the desired index
l1.insert(2, 33333) # Insert 33333 such that its index in the list is 2
print(l1)

# pop : pop is used to delete a particular value from the list 
l1.pop(3)
print(l1)

# remove  : remove a particular value from the list
l1.remove(200)
print(l1)