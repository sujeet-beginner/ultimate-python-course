class Employee:
    langauge = "Py"  # This is a Class attribute
    Salary = 1200000


sujeet = Employee()
sujeet.name = "Sujeet"    # This is a Class attribute
print(sujeet.name, sujeet.langauge, sujeet.Salary)


rohan = Employee()
rohan.name = "Rohan Rororo Zoro"
print(roahn.name, rohan.langauge, rohan.Salary)



# Here name is Object attribute and salary and langauage are Class attributes as they directly belong to the class